const char *util_hex2str(const void *buf, size_t len)
{
    int    i                = 0;
    const  uint8_t *b       = buf;
    static char str[129]    = {0};
    static const char hex[] = "0123456789abcdef";

    len = MIN(len, (sizeof(str) - 1) / 2);

    for (i = 0; i < len; i++) {
        str[i * 2]     = hex[b[i] >> 4];
        str[i * 2 + 1] = hex[b[i] & 0xf];
    }

    str[i * 2] = '\0';

    return str;
}
